        return "⏱️ រយៈពេលកំណត់៖ ៣ នាទី\n📏 កម្រិតពាក្យ៖ សរសេរប្រហែល ~៤០០ ទៅ ៤៥០ ពាក្យ (ពន្យល់ស៊ីជម្រៅ មានឧទាហរណ៍ជាក់ស្តែង ត្រូវតាមពេលវេលា ៣ នាទី)។"
